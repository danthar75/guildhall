describe("Serialize", function()
  local S
  before_each(function() local ns = {}; loadAddonFile(ns, "Guildhall/Core/Serialize.lua"); S = ns.Serialize end)
  it("round-trips nested values", function()
    local v = { id = "p1:2", v = 3, del = false, d = { note = "a|b\n:{}\\", qty = -4.5, list = { 1, "two" } } }
    assert.same(v, S.Decode(S.Encode(v)))
  end)
  it("round-trips floats exactly", function()
    for _, n in ipairs({ 0.1, 1 / 3, -1e300, 123456789012, 2 ^ 53 }) do
      assert.equal(n, S.Decode(S.Encode(n)))
    end
  end)
  it("round-trips scalars, empty table, delimiters", function()
    assert.equal(true, S.Decode(S.Encode(true)))
    assert.equal(false, S.Decode(S.Encode(false)))
    assert.same({}, S.Decode(S.Encode({})))
    assert.equal("", S.Decode(S.Encode("")))
    assert.equal(";\;{}", S.Decode(S.Encode(";\;{}")))
    assert.equal("Thálwyn", S.Decode(S.Encode("Thálwyn")))
  end)
  it("never emits NUL", function()
    assert.is_nil(S.Encode({ s = "x\0y" }):find("\0", 1, true))
    assert.equal("x\0y", S.Decode(S.Encode({ s = "x\0y" })).s)
  end)
  it("decode returns nil on garbage", function()
    assert.is_nil((S.Decode("}{not valid")))
    assert.is_nil((S.Decode("")))
    local v, err = S.Decode("}{not valid")
    assert.is_string(err)
  end)
  it("decode rejects truncated input and trailing junk", function()
    local enc = S.Encode({ a = "hello", b = { 1, 2, 3 } })
    for i = 1, #enc - 1 do assert.is_nil((S.Decode(enc:sub(1, i)))) end
    assert.is_nil((S.Decode(enc .. "x")))
    assert.is_nil((S.Decode(123)))
  end)
end)

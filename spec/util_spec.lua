describe("Util", function()
  local U
  before_each(function() local ns = {}; loadAddonFile(ns, "Guildhall/Core/Util.lua"); U = ns.Util end)
  it("Hash is deterministic and spreads", function()
    assert.equal(U.Hash("abc"), U.Hash("abc"))
    assert.are_not.equal(U.Hash("abc"), U.Hash("abd"))
    assert.is_true(U.Hash(string.rep("z", 500)) < 2147483647)
  end)
  it("FullName normalizes", function()
    assert.equal("Thálwyn-ArgentDawn", U.FullName("Thálwyn", "Argent Dawn"))
    assert.equal("Brakka-Realm", U.FullName("Brakka-Realm", "Other"))
    assert.equal("Mireth-Home", U.FullName("Mireth", nil, "Home"))
    assert.equal("A-DarkIrons", U.FullName("A", "Dark Iron's"))
  end)
  it("ItemName strips links", function()
    local link = "|cffa335ee|Hitem:14152::::::::60:::::|h[Robe of the Archmage]|h|r"
    assert.equal("Robe of the Archmage", U.ItemName(link))
    assert.is_true(U.IsItemLink(link))
    assert.is_false(U.IsItemLink("Runecloth"))
    assert.equal("Runecloth", U.ItemName("  Runecloth "))
  end)
  it("IsItemLink accepts exactly one whole item link (M7)", function()
    local link = "|cffa335ee|Hitem:14152::::::::60:::::|h[Robe of the Archmage]|h|r"
    assert.is_true(U.IsItemLink(link))
    assert.is_true(U.IsItemLink("|cnIQ4:|Hitem:19019::::::::80:::::|h[Thunderfury]|h|r"))
    assert.is_true(U.IsItemLink("|cff1eff00|Hitem:190396::::::::70:::::::::|h[Serevite Ore |A:Professions-ChatIcon-Quality-Tier2:17:15::1|a]|h|r"))
    assert.is_true(U.IsItemLink("|cffffffff|Hitem:-5:0|h[Odd]|h|r"))
    assert.is_false(U.IsItemLink("|TInterface\\Icons\\X:64|t" .. link))
    assert.is_false(U.IsItemLink(link .. "|cffff0000 FREE GOLD|r"))
    assert.is_false(U.IsItemLink(link .. link))
    assert.is_false(U.IsItemLink("|cffa335ee|Hitem:1|h[a|Hspell:1|h]|h|r"))
    assert.is_false(U.IsItemLink("|cffa335ee|Hitem:1|h[]|h|r"))
    assert.is_false(U.IsItemLink("|cffa335ee|Hspell:1|h[Fireball]|h|r"))
    assert.is_false(U.IsItemLink("x |Hitem:1|h[a]|h"))
    assert.is_false(U.IsItemLink(nil))
  end)
  it("Escape doubles every pipe so text renders literally", function()
    assert.equal("a||Tb||t", U.Escape("a|Tb|t"))
    assert.equal("plain", U.Escape("plain"))
    assert.equal("", U.Escape(nil))
  end)
  it("DisplayName drops the realm suffix for display", function()
    assert.equal("Dor", U.DisplayName("Dor-Realm"))
    assert.equal("Dor", U.DisplayName("Dor"))
    assert.equal("Dor", U.DisplayName("Dor-Some-Realm"))
    assert.is_nil(U.DisplayName(nil))
  end)

  it("ItemIdFromLink reads item links only", function()
    assert.equal(14152, U.ItemIdFromLink("|cffa335ee|Hitem:14152::::::::60:::::|h[Robe of the Archmage]|h|r"))
    assert.is_nil(U.ItemIdFromLink("|cffffd000|Henchant:7418|h[Enchanting: Runed Copper Rod]|h|r"))
    assert.is_nil(U.ItemIdFromLink("Runecloth"))
  end)
  it("Fill replaces known keys only", function()
    assert.equal("a X {y}", U.Fill("a {x} {y}", { x = "X" }))
  end)
  it("Trim and DeepCopy", function()
    assert.equal("a b", U.Trim("  a b\n"))
    local t = { a = { 1, 2 } }
    local c = U.DeepCopy(t)
    assert.same(t, c)
    assert.not_equal(t.a, c.a)
  end)
end)
